// Creating, saving and exporting a play session (browser side).

import { personaById } from "./org";
import type { ChatMessage, GraduateProfile, Scenario, Session } from "./types";
import { SKILLS, YOU } from "./types";

const STORAGE_KEY = "firstshift.session.v1";

export const newId = () => Math.random().toString(36).slice(2, 10);

export const firstName = (name: string) => name.trim().split(/\s+/)[0] || "there";

function fillName<T extends { text: string }>(items: T[], name: string): T[] {
  return items.map((m) => ({ ...m, text: m.text.replaceAll("{name}", name) }));
}

export function createSession(
  profile: GraduateProfile,
  scenario: Scenario,
  source: Session["source"],
): Session {
  const name = firstName(profile.name);
  const s: Scenario = {
    ...scenario,
    kickoff: fillName(scenario.kickoff, name),
    curveballs: fillName(scenario.curveballs, name),
  };
  const now = Date.now();
  const messages: ChatMessage[] = s.kickoff.map((k, i) => ({
    id: newId(),
    channel: k.channel,
    from: k.from,
    text: k.text,
    at: now + i,
  }));
  return {
    version: 1,
    id: newId(),
    source,
    profile,
    scenario: s,
    messages,
    revealedFactIds: [],
    firedCurveballIds: [],
    orgEvents: [],
    deliverable: "",
    startedAt: now,
  };
}

export function loadSession(): Session | null {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (!raw) return null;
    const s = JSON.parse(raw) as Session;
    return s?.version === 1 && s.scenario ? s : null;
  } catch {
    return null;
  }
}

export function saveSession(s: Session | null) {
  try {
    if (s) localStorage.setItem(STORAGE_KEY, JSON.stringify(s));
    else localStorage.removeItem(STORAGE_KEY);
  } catch {
    // storage full or blocked: the session still works in memory
  }
}

export function parseSessionFile(text: string): Session {
  const s = JSON.parse(text) as Session;
  if (s?.version !== 1 || !s.scenario || !Array.isArray(s.messages)) {
    throw new Error("This file is not a FirstShift session.");
  }
  return s;
}

const time = (at: number) =>
  new Date(at).toLocaleTimeString("en-PK", { hour: "2-digit", minute: "2-digit" });

/** Plain-text transcript of the whole shift (and the report, if graded). */
export function sessionTranscript(session: Session): string {
  const { scenario: s, profile } = session;
  const who = (from: string) => {
    if (from === YOU) return `${profile.name} (you)`;
    const p = personaById(s, from);
    return p ? `${p.name} (${p.title})` : "System";
  };
  const lines: string[] = [
    "FIRSTSHIFT: SHIFT TRANSCRIPT",
    "============================",
    `Graduate: ${profile.name} | Degree: ${profile.degree} | Target role: ${profile.targetRole}`,
    `Company: ${s.company.name} (fictional), ${s.company.industry}, ${s.company.city}`,
    `Your title: ${s.graduateTitle}`,
    `Started: ${new Date(session.startedAt).toLocaleString("en-PK")}`,
    `Scenario: ${session.source === "sample" ? "pre-written sample" : "generated by Gemini"}`,
    "",
    `TASK: ${s.task.title}`,
    s.task.brief,
    `Deliverable: ${s.task.deliverable}`,
    `Deadline: ${s.task.deadline}`,
    "",
    "TEAM",
    ...s.personas.map((p) => `- ${p.name}, ${p.title}${p.isExternal ? " (external)" : ""}`),
    "",
    "MESSAGES",
    ...session.messages.map(
      (m) =>
        `[${time(m.at)}] #${m.channel.startsWith("dm:") ? `dm-${personaById(s, m.channel.slice(3))?.name ?? "?"}` : m.channel}${m.kind === "curveball" ? " [UPDATE]" : ""} ${who(m.from)}: ${m.text}`,
    ),
    "",
    "DELIVERABLE",
    session.deliverable.trim() || "(not submitted yet)",
  ];

  const r = session.report;
  if (r) {
    lines.push(
      "",
      "JOB-READINESS REPORT (AI-generated practice feedback, not a hiring decision)",
      `Overall: ${r.overall}/100 (${r.verdict})`,
      r.summary,
      "",
      ...SKILLS.map(({ id, label }) => {
        const k = r.skills.find((x) => x.id === id);
        return `- ${label}: ${k?.score ?? 0}/10. ${k?.feedback ?? ""} Evidence: "${k?.evidence ?? ""}"`;
      }),
      "",
      "30-day plan:",
      ...r.plan.map((w) => `Week ${w.week}: ${w.focus}. ${w.actions.join("; ")}`),
    );
  }
  return lines.join("\n");
}

export function downloadFile(filename: string, text: string, type = "text/plain") {
  const blob = new Blob([text], { type: `${type};charset=utf-8` });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  URL.revokeObjectURL(url);
}

export function fileStem(session: Session) {
  const who = firstName(session.profile.name).toLowerCase().replace(/[^a-z0-9]/g, "") || "graduate";
  return `firstshift-${who}-${new Date(session.startedAt).toISOString().slice(0, 10)}`;
}
